export const getProductBySlug = (slug: string): Product | undefined => {
  if (!slug) return undefined;
  return products.find(
    (p) => p.slug === slug || p.id === slug || p.slug === slug.toLowerCase()
  );
};

export const getProductsByCollection = (collectionSlug: string): Product[] => {
  if (!collectionSlug) return [];
  const normalized = normalizeCollectionSlug(collectionSlug);
  const shortCollection = normalized.replace("-series", "").replace("-attars", "");
  return products.filter(
    (p) =>
      p.collectionSlug === normalized ||
      p.collection === shortCollection ||
      p.collectionSlug === collectionSlug
  );
};

export const getProductsByFormat = (format: string): Product[] => {
  return products.filter((p) => p.format === format);
};

export const getFeaturedProducts = (): Product[] => {
  return products.filter((p) => p.featured && !p.isPlaceholder);
};
